#!/usr/bin/env bash
#
# B-29.5 — symbol-graph scale benchmark driver.
# Sibling to run_all_tiers.sh (which targets phase_b31_5 resumable
# indexing). C-20 DECISION-D1: kept as a sibling rather than extending
# run_all_tiers.sh to keep blast radius small. The B-31.5 path writes
# phase_b31_5_scale.toml; this script writes phase_b29_5_scale.toml.
#
# Pre-condition: ELAI_SCALE_FIXTURE_ROOT must point to a clone root
# containing four sub-directories (linux/, chromium/, vscode/, postgres/).
# When ELAI_SCALE_FIXTURE_ROOT is unset the script exits 2 with a clear
# diagnostic instead of fabricating tier rows.
#
# Per-tier action: run `cargo bench -p elai-knowledge
# --bench symbol_graph_scale -- --tier <name>` once per tier with the
# project_root override pointing at the matching sub-directory. Capture
# p50/p95/p99 for impact_radius / call_flow / symbol_context / list_symbols
# plus peak_rss_mb. Emit a TOML appendix to phase_b29_5_scale.toml.
#
# Usage:
#   ELAI_SCALE_FIXTURE_ROOT=/data/repos run_b29_5_symbol_graph.sh
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
METRICS_FILE="${METRICS_FILE:-$REPO_ROOT/metrics/phase_b29_5_scale.toml}"

if [[ -z "${ELAI_SCALE_FIXTURE_ROOT:-}" ]]; then
    echo "run_b29_5_symbol_graph: ELAI_SCALE_FIXTURE_ROOT not set; aborting" >&2
    echo "                        export it to a clone root with linux/chromium/vscode/postgres sub-dirs" >&2
    exit 2
fi

ROOT="$ELAI_SCALE_FIXTURE_ROOT"
NOW=$(date +%s)
TIERS=(linux chromium vscode postgres)

# Track which tiers actually ran vs. were skipped due to missing fixture.
RAN=()
SKIPPED=()

for tier in "${TIERS[@]}"; do
    TIER_PATH="$ROOT/$tier"
    if [[ ! -d "$TIER_PATH" ]]; then
        echo "run_b29_5_symbol_graph: $tier — missing fixture at $TIER_PATH; skipping" >&2
        SKIPPED+=("$tier")
        continue
    fi
    echo "run_b29_5_symbol_graph: $tier — running bench against $TIER_PATH" >&2

    # The bench binary handles result aggregation via env vars consumed
    # by symbol_graph_scale.rs (ELAI_SCALE_FIXTURE_ROOT + ELAI_SCALE_TIER).
    if ELAI_SCALE_TIER="$tier" \
       cargo bench --manifest-path "$REPO_ROOT/Cargo.toml" \
           -p elai-knowledge --bench symbol_graph_scale \
           >/tmp/elai_b29_5_${tier}.log 2>&1; then
        RAN+=("$tier")
        echo "run_b29_5_symbol_graph: $tier — bench PASS" >&2
    else
        echo "run_b29_5_symbol_graph: $tier — bench FAILED; see /tmp/elai_b29_5_${tier}.log" >&2
        SKIPPED+=("$tier")
    fi
done

# Append a [c20_scale_run] block to phase_b29_5_scale.toml. The bench
# itself writes per-tier `[<tier>]` blocks (it owns the format). We only
# write the run-summary metadata so the auditor can see which tiers ran.
mkdir -p "$(dirname "$METRICS_FILE")"
{
    echo ""
    echo "# Generated by scripts/scale_test/run_b29_5_symbol_graph.sh"
    echo "[c20_scale_run]"
    echo "fired = true"
    echo "generated_at_unix_secs = $NOW"
    if [[ ${#RAN[@]} -eq 0 ]]; then
        echo "tiers_ran = []"
    else
        printf 'tiers_ran = ['
        for i in "${!RAN[@]}"; do
            if [[ $i -eq 0 ]]; then
                printf '"%s"' "${RAN[$i]}"
            else
                printf ', "%s"' "${RAN[$i]}"
            fi
        done
        printf ']\n'
    fi
    if [[ ${#SKIPPED[@]} -eq 0 ]]; then
        echo "tiers_skipped = []"
    else
        printf 'tiers_skipped = ['
        for i in "${!SKIPPED[@]}"; do
            if [[ $i -eq 0 ]]; then
                printf '"%s"' "${SKIPPED[$i]}"
            else
                printf ', "%s"' "${SKIPPED[$i]}"
            fi
        done
        printf ']\n'
    fi
    echo "fixture_root = \"$ROOT\""
} >> "$METRICS_FILE"

echo "run_b29_5_symbol_graph: appended summary to $METRICS_FILE" >&2

# Exit 0 only when at least one tier ran successfully.
if [[ ${#RAN[@]} -eq 0 ]]; then
    exit 1
fi
exit 0
