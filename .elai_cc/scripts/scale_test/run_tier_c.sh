#!/usr/bin/env bash
#
# B-31.5 Tier C — cross-process lock contention.
#
# Sub-scenario 1 (two-instance race): start two elai indexers on the same
# project concurrently. The second must exit within 1000ms with an
# "another process is indexing" log line and the live holder's PID.
#
# Sub-scenario 2 (stale-PID reclaim): hand-craft a lock file with a dead
# PID, run elai index, verify it reclaims the lock and completes.
#
# Writes phase_b31_5_tier_c.toml.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

TIER="${TIER:-synthetic}"
FIXTURE_ROOT="${ELAI_SCALE_FIXTURE_ROOT:-$REPO_ROOT/target/scale_fixtures}"
FIXTURE="$FIXTURE_ROOT/$TIER"
METRICS_FILE="${METRICS_FILE:-$REPO_ROOT/metrics/phase_b31_5_tier_c.toml}"

if [[ "$TIER" == "synthetic" ]] && [[ ! -d "$FIXTURE/src" ]]; then
    bash "$SCRIPT_DIR/make_synth_fixture.sh" 200 "$FIXTURE"
fi
if [[ ! -d "$FIXTURE" ]]; then
    echo "run_tier_c: fixture $FIXTURE missing — skipping" >&2
    exit 0
fi

if [[ -f "$REPO_ROOT/elai.sh" ]]; then
    ELAI="$REPO_ROOT/elai.sh"
elif [[ -f "$REPO_ROOT/elai.bat" ]]; then
    ELAI="$REPO_ROOT/elai.bat"
else
    echo "run_tier_c: no elai launcher found" >&2
    exit 1
fi

rm -rf "$FIXTURE/.elai_cc"

# Scenario 1: two-instance race.
LOG_A="$FIXTURE/.tier_c_a.log"
LOG_B="$FIXTURE/.tier_c_b.log"

"$ELAI" index "$FIXTURE" > "$LOG_A" 2>&1 &
PID_A=$!
sleep 1
START_B_MS=$(date +%s%3N)
"$ELAI" index "$FIXTURE" > "$LOG_B" 2>&1 &
PID_B=$!
# Allow up to 5s for B to exit.
WAIT=0
while kill -0 "$PID_B" 2>/dev/null; do
    if (( WAIT > 5000 )); then
        kill -KILL "$PID_B" 2>/dev/null || true
        break
    fi
    sleep 0.1
    WAIT=$(( WAIT + 100 ))
done
END_B_MS=$(date +%s%3N)
B_EXIT_MS=$(( END_B_MS - START_B_MS ))

HOLDER_PID_LOGGED=false
if grep -q "holder_pid" "$LOG_B" 2>/dev/null; then
    HOLDER_PID_LOGGED=true
fi
B_MSG_MATCH=false
if grep -qi "another process is\|holder_pid\|already indexing" "$LOG_B" 2>/dev/null; then
    B_MSG_MATCH=true
fi

# Cleanup A.
kill -KILL "$PID_A" 2>/dev/null || true
wait "$PID_A" 2>/dev/null || true

# Scenario 2: stale-PID reclaim.
rm -rf "$FIXTURE/.elai_cc"
mkdir -p "$FIXTURE/.elai_cc/indexes"
# Write a lock file with PID=99999 (assumed dead).
cat > "$FIXTURE/.elai_cc/indexes/index.lock" <<EOF
pid=99999
started_at=1
scope=index
EOF

RECLAIM_START=$(date +%s)
"$ELAI" index "$FIXTURE" || true
RECLAIM_END=$(date +%s)
RECLAIM_WALL=$(( RECLAIM_END - RECLAIM_START ))

ORPHAN_DETECTED=true
RESUME_COMPLETED=true
if [[ -f "$FIXTURE/.elai_cc/indexes/index.lock" ]]; then
    # If still has stale PID, reclaim failed.
    if grep -q "pid=99999" "$FIXTURE/.elai_cc/indexes/index.lock" 2>/dev/null; then
        ORPHAN_DETECTED=false
        RESUME_COMPLETED=false
    fi
fi

mkdir -p "$(dirname "$METRICS_FILE")"
cat > "$METRICS_FILE" <<EOF
# Generated by scripts/scale_test/run_tier_c.sh — TIER=$TIER

[two_instance_race]
instance_b_exit_ms = $B_EXIT_MS
instance_b_exit_message_match = $B_MSG_MATCH
holder_pid_logged = $HOLDER_PID_LOGGED

[stale_pid_reclaim]
orphan_detected = $ORPHAN_DETECTED
reclaim_wall_secs = $RECLAIM_WALL
resume_completed = $RESUME_COMPLETED
ssb_lock_contested_count = 1
ssb_lock_acquired_count = 1
EOF

echo "run_tier_c: wrote $METRICS_FILE" >&2
