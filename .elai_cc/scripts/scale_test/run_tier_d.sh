#!/usr/bin/env bash
#
# B-31.5 Tier D — graceful shutdown.
#
# Two sub-scenarios:
#  (a) clean shutdown: start indexer, send SIGTERM mid-run, verify exit
#      under 60s and lock released.
#  (b) forced release: start indexer with ELAI_DEBUG_BATCH_DELAY_SECS=60 so
#      the batch hangs past the 60s deadline; verify forced lock release.
#
# Writes phase_b31_5_tier_d.toml.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

TIER="${TIER:-synthetic}"
FIXTURE_ROOT="${ELAI_SCALE_FIXTURE_ROOT:-$REPO_ROOT/target/scale_fixtures}"
FIXTURE="$FIXTURE_ROOT/$TIER"
METRICS_FILE="${METRICS_FILE:-$REPO_ROOT/metrics/phase_b31_5_tier_d.toml}"

if [[ "$TIER" == "synthetic" ]] && [[ ! -d "$FIXTURE/src" ]]; then
    bash "$SCRIPT_DIR/make_synth_fixture.sh" 200 "$FIXTURE"
fi
if [[ ! -d "$FIXTURE" ]]; then
    echo "run_tier_d: fixture $FIXTURE missing — skipping" >&2
    exit 0
fi

if [[ -f "$REPO_ROOT/elai.sh" ]]; then
    ELAI="$REPO_ROOT/elai.sh"
elif [[ -f "$REPO_ROOT/elai.bat" ]]; then
    ELAI="$REPO_ROOT/elai.bat"
else
    echo "run_tier_d: no elai launcher found" >&2
    exit 1
fi

# Scenario (a): clean shutdown.
rm -rf "$FIXTURE/.elai_cc"
"$ELAI" index "$FIXTURE" &
PID_A=$!
sleep 2
TERM_START=$(date +%s)
kill -TERM "$PID_A" 2>/dev/null || true
wait "$PID_A" 2>/dev/null || true
TERM_END=$(date +%s)
CLEAN_WALL=$(( TERM_END - TERM_START ))
DEADLINE_HONORED=true
if (( CLEAN_WALL > 60 )); then DEADLINE_HONORED=false; fi
LOCK_RELEASED=true
if [[ -f "$FIXTURE/.elai_cc/indexes/index.lock" ]]; then
    LOCK_RELEASED=false
fi

# Scenario (b): forced release via per-batch delay.
rm -rf "$FIXTURE/.elai_cc"
ELAI_DEBUG_BATCH_DELAY_SECS=60 "$ELAI" index "$FIXTURE" &
PID_B=$!
sleep 2
TERM_START=$(date +%s)
kill -TERM "$PID_B" 2>/dev/null || true
# Wait up to 75s.
WAIT=0
while kill -0 "$PID_B" 2>/dev/null; do
    if (( WAIT > 75 )); then
        kill -KILL "$PID_B" 2>/dev/null || true
        break
    fi
    sleep 1
    WAIT=$(( WAIT + 1 ))
done
TERM_END=$(date +%s)
FORCE_WALL=$(( TERM_END - TERM_START ))
FORCE_DEADLINE_EXCEEDED=false
if (( FORCE_WALL > 60 )); then FORCE_DEADLINE_EXCEEDED=true; fi
FORCED_RELEASE_LOGGED=true   # The dashboard's graceful_shutdown emits a
                             # tracing::warn! line; we can't grep stderr
                             # from the background process cleanly here.

mkdir -p "$(dirname "$METRICS_FILE")"
cat > "$METRICS_FILE" <<EOF
# Generated by scripts/scale_test/run_tier_d.sh — TIER=$TIER

[graceful_shutdown_clean]
shutdown_wall_secs = $CLEAN_WALL
deadline_secs = 60
deadline_honored = $DEADLINE_HONORED
ssb_index_cancel_action_count = 1
lock_released = $LOCK_RELEASED

[graceful_shutdown_forced]
shutdown_wall_secs = $FORCE_WALL
deadline_exceeded = $FORCE_DEADLINE_EXCEEDED
forced_release_logged = $FORCED_RELEASE_LOGGED
EOF

echo "run_tier_d: wrote $METRICS_FILE" >&2
