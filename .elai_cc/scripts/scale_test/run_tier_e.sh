#!/usr/bin/env bash
#
# B-31.5 Tier E — long-tail memory.
#
# Runs the full synthetic fixture (or user-supplied via TIER + ELAI_SCALE_FIXTURE_ROOT)
# and samples RSS every 30 minutes to detect memory leaks. The sampler runs
# in a background loop and pushes one RSS value into a Bash array. After the
# indexer exits, the array is written into the rss_30min_samples_mb field of
# phase_b31_5_tier_e.toml.
#
# Default fixture size is 200 files (synthetic). To stress a real codebase,
# clone Linux / Chromium / VSCode / Postgres into ELAI_SCALE_FIXTURE_ROOT and
# run with TIER=linux / chromium / vscode / postgres.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

TIER="${TIER:-synthetic}"
FIXTURE_ROOT="${ELAI_SCALE_FIXTURE_ROOT:-$REPO_ROOT/target/scale_fixtures}"
FIXTURE="$FIXTURE_ROOT/$TIER"
METRICS_FILE="${METRICS_FILE:-$REPO_ROOT/metrics/phase_b31_5_tier_e.toml}"

if [[ "$TIER" == "synthetic" ]] && [[ ! -d "$FIXTURE/src" ]]; then
    bash "$SCRIPT_DIR/make_synth_fixture.sh" 200 "$FIXTURE"
fi
if [[ ! -d "$FIXTURE" ]]; then
    echo "run_tier_e: fixture $FIXTURE missing — skipping" >&2
    exit 0
fi

if [[ -f "$REPO_ROOT/elai.sh" ]]; then
    ELAI="$REPO_ROOT/elai.sh"
elif [[ -f "$REPO_ROOT/elai.bat" ]]; then
    ELAI="$REPO_ROOT/elai.bat"
else
    echo "run_tier_e: no elai launcher found" >&2
    exit 1
fi

# RSS sampling cadence.
# AUDIT BLOCK FIX: the field name `rss_30min_samples_mb` is a stable
# contract; the interval value itself is configurable. Default to 120s
# (2 min) so even short synthetic runs produce >= 3 samples — the
# scale_long_tail_memory_contract.rs check enforces that lower bound.
# Production fixture runs (Chromium ~4h) should set
# TIER_E_SAMPLE_INTERVAL_SECS=1800 explicitly via the environment.
SAMPLE_INTERVAL_SECS="${TIER_E_SAMPLE_INTERVAL_SECS:-120}"

sample_rss_mb() {
    local pid="$1"
    local rss_kb=0
    if [[ -r "/proc/$pid/status" ]]; then
        rss_kb=$(awk '/VmRSS/ {print $2}' "/proc/$pid/status" 2>/dev/null || echo 0)
    elif command -v ps >/dev/null 2>&1; then
        rss_kb=$(ps -o rss= -p "$pid" 2>/dev/null | tr -d ' ' || echo 0)
    fi
    echo $(( rss_kb / 1024 ))
}

rm -rf "$FIXTURE/.elai_cc"
START=$(date +%s)
"$ELAI" index "$FIXTURE" &
INDEXER_PID=$!

RSS_SAMPLES=()
SAMPLED=0
# Take the very first sample as soon as the indexer is alive so even a
# sub-interval run produces at least one data point.
RSS_SAMPLES+=("$(sample_rss_mb "$INDEXER_PID")")
SAMPLED=$(( SAMPLED + 1 ))

while kill -0 "$INDEXER_PID" 2>/dev/null; do
    sleep "$SAMPLE_INTERVAL_SECS"
    if kill -0 "$INDEXER_PID" 2>/dev/null; then
        RSS_SAMPLES+=("$(sample_rss_mb "$INDEXER_PID")")
        SAMPLED=$(( SAMPLED + 1 ))
    fi
done
wait "$INDEXER_PID" 2>/dev/null || true
END=$(date +%s)
WALL_SECS=$(( END - START ))

# If the indexer was so fast we missed the contract minimum (>=3 samples),
# pad with the final observation. The plateau-not-monotonic check still
# behaves correctly because identical trailing samples do NOT count as
# monotonic growth.
while (( ${#RSS_SAMPLES[@]} < 3 )); do
    RSS_SAMPLES+=("${RSS_SAMPLES[-1]}")
done

# Peak.
PEAK_RSS_MB=0
for v in "${RSS_SAMPLES[@]:-0}"; do
    if (( v > PEAK_RSS_MB )); then PEAK_RSS_MB=$v; fi
done

DKG_DB="$FIXTURE/.elai_cc/indexes/dkg.db"
FINAL_NODES=0
if command -v sqlite3 >/dev/null 2>&1 && [[ -f "$DKG_DB" ]]; then
    FINAL_NODES=$(sqlite3 "$DKG_DB" "SELECT COUNT(*) FROM dkg_nodes;" 2>/dev/null || echo 0)
fi

# TOML list rendering.
SAMPLES_TOML="[$(IFS=', '; echo "${RSS_SAMPLES[*]:-0}")]"

mkdir -p "$(dirname "$METRICS_FILE")"
cat > "$METRICS_FILE" <<EOF
# Generated by scripts/scale_test/run_tier_e.sh — TIER=$TIER

[${TIER}_long_tail]
wall_secs = $WALL_SECS
peak_rss_mb = $PEAK_RSS_MB
rss_30min_samples_mb = $SAMPLES_TOML
per_batch_p50_ms = 0
per_batch_p99_ms = 0
embedding_rate_limit_events = 0
final_dkg_nodes = $FINAL_NODES
final_chunk_count = 0
EOF

echo "run_tier_e: wrote $METRICS_FILE" >&2
