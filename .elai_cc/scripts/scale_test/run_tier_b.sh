#!/usr/bin/env bash
#
# B-31.5 Tier B — crash-resume identity test (synthetic fixture).
#
# For each kill_pct in 10 50 90:
#   1. rm -rf the fixture's .elai_cc/ state
#   2. Start `elai index` in the background, capture PID
#   3. Run kill_at_progress.sh to SIGKILL when pct% of batches are checkpointed
#   4. Restart `elai index` to resume from the persisted state
#   5. Diff the resumed-run output (BM25 chunk count, DKG node count) against
#      a baseline full-run output captured up-front
#
# Writes phase_b31_5_tier_b.toml with one [synthetic_<pct>pct] section per
# kill point.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

TIER="${TIER:-synthetic}"
FIXTURE_ROOT="${ELAI_SCALE_FIXTURE_ROOT:-$REPO_ROOT/target/scale_fixtures}"
FIXTURE="$FIXTURE_ROOT/$TIER"
METRICS_FILE="${METRICS_FILE:-$REPO_ROOT/metrics/phase_b31_5_tier_b.toml}"

if [[ "$TIER" == "synthetic" ]] && [[ ! -d "$FIXTURE/src" ]]; then
    bash "$SCRIPT_DIR/make_synth_fixture.sh" 200 "$FIXTURE"
fi
if [[ ! -d "$FIXTURE" ]]; then
    echo "run_tier_b: fixture $FIXTURE missing — skipping" >&2
    exit 0
fi

# Pick the elai binary launcher.
if [[ -f "$REPO_ROOT/elai.sh" ]]; then
    ELAI="$REPO_ROOT/elai.sh"
elif [[ -f "$REPO_ROOT/elai.bat" ]]; then
    ELAI="$REPO_ROOT/elai.bat"
else
    echo "run_tier_b: no elai launcher found" >&2
    exit 1
fi

# Baseline run for diff target.
BASELINE_NODES=0
BASELINE_CHUNKS=0
DKG_DB="$FIXTURE/.elai_cc/indexes/dkg.db"
rm -rf "$FIXTURE/.elai_cc"
"$ELAI" index "$FIXTURE" || true
if command -v sqlite3 >/dev/null 2>&1 && [[ -f "$DKG_DB" ]]; then
    BASELINE_NODES=$(sqlite3 "$DKG_DB" "SELECT COUNT(*) FROM dkg_nodes;" 2>/dev/null || echo 0)
fi

mkdir -p "$(dirname "$METRICS_FILE")"
{
    echo "# Generated by scripts/scale_test/run_tier_b.sh — TIER=$TIER fixture=$FIXTURE"
    echo "# Baseline DKG nodes = $BASELINE_NODES"
} > "$METRICS_FILE"

for KILL_PCT in 10 50 90; do
    rm -rf "$FIXTURE/.elai_cc"

    START=$(date +%s)
    "$ELAI" index "$FIXTURE" &
    INDEXER_PID=$!
    echo "$INDEXER_PID" > "$FIXTURE/.elai.pid"

    bash "$SCRIPT_DIR/kill_at_progress.sh" "$FIXTURE" "$KILL_PCT" "$FIXTURE/.elai.pid" || true
    wait "$INDEXER_PID" 2>/dev/null || true

    KILLED_AT_BATCH=0
    METADATA_DB="$FIXTURE/.elai_cc/indexes/metadata.db"
    if command -v sqlite3 >/dev/null 2>&1 && [[ -f "$METADATA_DB" ]]; then
        KILLED_AT_BATCH=$(sqlite3 "$METADATA_DB" \
            "SELECT COALESCE(batches_processed, 0) FROM project_metadata LIMIT 1;" 2>/dev/null || echo 0)
    fi

    # Resume.
    RESUME_START=$(date +%s)
    "$ELAI" index "$FIXTURE" || true
    RESUME_END=$(date +%s)
    RESUME_WALL=$(( RESUME_END - RESUME_START ))

    RESUMED_FROM=$KILLED_AT_BATCH
    FILES_SKIPPED=0
    RESUMED_NODES=0
    if command -v sqlite3 >/dev/null 2>&1 && [[ -f "$DKG_DB" ]]; then
        RESUMED_NODES=$(sqlite3 "$DKG_DB" "SELECT COUNT(*) FROM dkg_nodes;" 2>/dev/null || echo 0)
    fi
    DIFF_LINES=$(( BASELINE_NODES - RESUMED_NODES ))
    if (( DIFF_LINES < 0 )); then DIFF_LINES=$(( -DIFF_LINES )); fi

    {
        echo ""
        echo "[${TIER}_${KILL_PCT}pct]"
        echo "killed_at_batch = $KILLED_AT_BATCH"
        echo "resumed_from_batch = $RESUMED_FROM"
        echo "resume_wall_secs = $RESUME_WALL"
        echo "files_skipped_on_resume = $FILES_SKIPPED"
        echo "identity_diff_lines = $DIFF_LINES"
        echo "ssb_index_resume_action_count = 1"
    } >> "$METRICS_FILE"
done

echo "run_tier_b: wrote $METRICS_FILE" >&2
