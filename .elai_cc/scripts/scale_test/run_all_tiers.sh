#!/usr/bin/env bash
#
# B-31.5 — orchestrator across all tiers. Runs A → B → C → D → E and
# aggregates pass/fail booleans into metrics/phase_b31_5_scale.toml.
#
# Each tier individually writes its own phase_b31_5_tier_{a,b,c,d,e}.toml.
# This script then reads those and produces a single summary file.
#
# Usage:
#   TIER=synthetic run_all_tiers.sh
#   ELAI_SCALE_FIXTURE_ROOT=/data/repos TIER=linux run_all_tiers.sh
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

TIER="${TIER:-synthetic}"
METRICS_FILE="${METRICS_FILE:-$REPO_ROOT/metrics/phase_b31_5_scale.toml}"

bash "$SCRIPT_DIR/run_tier_a.sh"
TIER_A_PASS=$?
bash "$SCRIPT_DIR/run_tier_b.sh"
TIER_B_PASS=$?
bash "$SCRIPT_DIR/run_tier_c.sh"
TIER_C_PASS=$?
bash "$SCRIPT_DIR/run_tier_d.sh"
TIER_D_PASS=$?
bash "$SCRIPT_DIR/run_tier_e.sh"
TIER_E_PASS=$?

# Convert non-zero exits to false.
[[ "$TIER_A_PASS" -eq 0 ]] && TIER_A_BOOL=true || TIER_A_BOOL=false
[[ "$TIER_B_PASS" -eq 0 ]] && TIER_B_BOOL=true || TIER_B_BOOL=false
[[ "$TIER_C_PASS" -eq 0 ]] && TIER_C_BOOL=true || TIER_C_BOOL=false
[[ "$TIER_D_PASS" -eq 0 ]] && TIER_D_BOOL=true || TIER_D_BOOL=false
[[ "$TIER_E_PASS" -eq 0 ]] && TIER_E_BOOL=true || TIER_E_BOOL=false

OVERALL=true
if [[ "$TIER_A_BOOL" != "true" ]] || [[ "$TIER_B_BOOL" != "true" ]] \
    || [[ "$TIER_C_BOOL" != "true" ]] || [[ "$TIER_D_BOOL" != "true" ]] \
    || [[ "$TIER_E_BOOL" != "true" ]]; then
    OVERALL=false
fi

NOW=$(date +%s)
mkdir -p "$(dirname "$METRICS_FILE")"
cat > "$METRICS_FILE" <<EOF
# Generated by scripts/scale_test/run_all_tiers.sh — TIER=$TIER

[summary]
tier_a_baseline_pass = $TIER_A_BOOL
tier_b_resume_identity_pass = $TIER_B_BOOL
tier_c_lock_contention_pass = $TIER_C_BOOL
tier_d_graceful_shutdown_pass = $TIER_D_BOOL
tier_e_long_tail_pass = $TIER_E_BOOL
overall_pass = $OVERALL

[fixture]
kind = "$TIER"
file_count = 200
source = "scripts/scale_test/make_synth_fixture.sh"

[provenance]
generated_at_unix_secs = $NOW
generated_by_session = "scripts/scale_test/run_all_tiers.sh"
elai_revision = "HEAD"

[notes]
production_scale_fixture_runs_required_followup = "manual run of Linux/Chromium/VSCode/Postgres via run_all_tiers.sh with ELAI_SCALE_FIXTURE_ROOT pointing to cloned repos"
EOF

echo "run_all_tiers: wrote $METRICS_FILE (overall_pass=$OVERALL)" >&2
