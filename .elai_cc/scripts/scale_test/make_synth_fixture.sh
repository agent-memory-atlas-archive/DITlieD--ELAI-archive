#!/usr/bin/env bash
#
# B-31.5 Tier-A/B/E synthetic fixture generator.
#
# Usage:
#   make_synth_fixture.sh <count> <output_dir>
#
# Generates <count> Rust source files at <output_dir>/src/mod_<N>.rs, each
# containing 50-500 deterministic-from-seed functions, plus a Cargo.toml and
# src/lib.rs at the root so the fixture is a valid Rust crate. The seed is
# derived from $1 (count) so a re-run with the same args produces an
# identical fixture — required by the Tier B "identity-on-resume" check.
#
# Windows note: run via Git Bash; on plain PowerShell use:
#   bash scripts/scale_test/make_synth_fixture.sh 200 "$env:TMP\synth"
set -euo pipefail

if [[ $# -lt 2 ]]; then
    echo "usage: make_synth_fixture.sh <count> <output_dir>" >&2
    exit 2
fi

COUNT="$1"
OUT_DIR="$2"

if ! [[ "$COUNT" =~ ^[0-9]+$ ]]; then
    echo "error: count must be a non-negative integer, got '$COUNT'" >&2
    exit 2
fi

mkdir -p "$OUT_DIR/src"

# Deterministic Cargo.toml.
cat > "$OUT_DIR/Cargo.toml" <<EOF
[package]
name = "elai_scale_synth"
version = "0.0.0"
edition = "2021"
publish = false

[lib]
path = "src/lib.rs"
EOF

# lib.rs declares every generated mod.
{
    echo "//! Synthetic fixture for B-31.5 scale benchmarks."
    echo "//! Generated by scripts/scale_test/make_synth_fixture.sh count=$COUNT"
    for ((i = 0; i < COUNT; i++)); do
        echo "pub mod mod_$i;"
    done
} > "$OUT_DIR/src/lib.rs"

# Per-file generator: 50..=500 fns of trivial bodies. Seed each file with its
# index so the count is reproducible.
for ((i = 0; i < COUNT; i++)); do
    # Deterministic "random" function count per file: (i * 31 + 50) mod 451.
    FN_COUNT=$(( (i * 31 + 50) % 451 + 50 ))
    {
        echo "// mod_$i — synthetic fixture, $FN_COUNT functions."
        for ((j = 0; j < FN_COUNT; j++)); do
            echo "pub fn synth_${i}_${j}() -> u64 { $((i * 1000 + j)) }"
        done
    } > "$OUT_DIR/src/mod_$i.rs"
done

echo "synthetic fixture: $COUNT files at $OUT_DIR" >&2
