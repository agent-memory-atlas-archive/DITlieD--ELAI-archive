//! E-37: Provenance tagging for untrusted content (OWASP LLM01 mitigation).
//!
//! Threads a `Provenance` tag through every string that flows from a tool
//! result, web fetch, MCP server, file upload, sandbox stdout, or memory
//! recall site to the model. The CaMeL-lite capability gate
//! (`capability_gate.rs`) consults this tag at destructive-tool dispatch
//! time and rejects calls whose argv carries non-`UserPrompt`/`System`
//! provenance.
//!
//! Design grounding: arXiv:2503.18813 (CaMeL: capability-based machine
//! learning) defines a capability calculus over provenance-tagged values;
//! ELAI ships a lite version (`allow_tool_with_origin`) that does NOT
//! require the full SMT solver. The full calculus is deferred to E-37.B.
//!
//! Pairs additively with E-30 `destructive_verb_allowlist::AllowlistVerdict`
//! — that module operates at T1 argv-regex level; this module operates at
//! semantic provenance-tag level. Both layers stay; different concerns.
//!
//! Sibling shape: `AllowlistVerdict` enum (variants with structured
//! reason + citation fields, serde-friendly, no anyhow strings).

use blake3::Hasher;
use serde::{Deserialize, Serialize};
use std::path::PathBuf;

/// Source category for a span of text. Used to thread trust level through
/// the orchestrator -> agent -> tool dispatch chain.
///
/// The wire serialization is `snake_case` so SSB payloads can carry the
/// label as `text_source_hash = blake3(label_bytes)[..8]` without colliding
/// with the source format.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case", tag = "kind")]
pub enum TextSource {
    /// Span entered by the live human user via the CLI / dashboard.
    UserPrompt,
    /// Span generated by the system (config files, internal prompts, ELAI
    /// system messages). Trusted at the same level as `UserPrompt`.
    System,
    /// Span from an MCP tool output (post-sanitize_result).
    ToolOutput { server_url: String, tool_name: String },
    /// Span from a web-fetched HTML / markdown / json body (post-extractor).
    Web { url: String },
    /// Span from a file upload (drag-drop into the dashboard, agent
    /// `read_file` call on a user-supplied path).
    File { source_path: PathBuf },
    /// Span from a sandbox subprocess stdout / stderr (bash, python -c, etc).
    SandboxOutput { sandbox_id: String },
    /// Span recalled from persistent memory (memory-bank/, RAG retrieval).
    Memory { source_key: String },
}

impl TextSource {
    /// Stable wire label used by the SSB hash field. Bound to the snake-case
    /// kind discriminant; payload fields are NOT mixed in (so two web spans
    /// from different URLs hash to the same label — the URL goes into a
    /// separate field on the SSB row).
    pub fn label(&self) -> &'static str {
        match self {
            Self::UserPrompt => "user_prompt",
            Self::System => "system",
            Self::ToolOutput { .. } => "tool_output",
            Self::Web { .. } => "web",
            Self::File { .. } => "file",
            Self::SandboxOutput { .. } => "sandbox_output",
            Self::Memory { .. } => "memory",
        }
    }

    /// blake3-prefix u64 of `label()` for SSB `text_source_hash` columns.
    pub fn label_blake3_prefix(&self) -> u64 {
        let mut h = Hasher::new();
        h.update(self.label().as_bytes());
        let out = h.finalize();
        let bytes = out.as_bytes();
        u64::from_le_bytes([
            bytes[0], bytes[1], bytes[2], bytes[3],
            bytes[4], bytes[5], bytes[6], bytes[7],
        ])
    }
}

/// Trust level a `Provenance` carries. The capability gate uses this to
/// decide whether destructive argv can run.
///
/// Sibling shape: matches `AllowlistVerdict` 3-tier (Allow / RequireApproval /
/// Deny) but at the provenance layer (a value HAS a trust, not the call).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TrustLevel {
    /// Fully trusted (user prompt, system message). Capability gate allows
    /// without question.
    Trusted,
    /// Recallable memory: indirectly trusted, but RAG retrieval can surface
    /// adversarial content if upstream-untrusted content was previously
    /// memorized. Capability gate allows non-destructive, requires
    /// approval for destructive.
    Recallable,
    /// External / untrusted (web, tool output, file upload, sandbox stdout).
    /// Capability gate rejects destructive argv that contains this trust
    /// level on ANY thread; emits `CapabilityGateRejected` SSB row.
    Untrusted,
}

impl TrustLevel {
    pub fn label(self) -> &'static str {
        match self {
            Self::Trusted => "trusted",
            Self::Recallable => "recallable",
            Self::Untrusted => "untrusted",
        }
    }

    pub fn label_blake3_prefix(self) -> u64 {
        let mut h = Hasher::new();
        h.update(self.label().as_bytes());
        let out = h.finalize();
        let bytes = out.as_bytes();
        u64::from_le_bytes([
            bytes[0], bytes[1], bytes[2], bytes[3],
            bytes[4], bytes[5], bytes[6], bytes[7],
        ])
    }
}

/// Provenance tag carried alongside a value through the dispatch chain.
/// The orchestrator threads `Provenanced<T>` through `task_runner.rs`
/// argv construction sites so the capability gate can inspect the trust
/// of every argument BEFORE the destructive tool fires.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct Provenance {
    pub source: TextSource,
    pub trust: TrustLevel,
}

impl Provenance {
    /// J-93 LEG-C: memory-retrieved fact with restored trust.
    pub fn from_memory_retrieved(source_key: impl Into<String>, trust: TrustLevel) -> Self {
        Self { source: TextSource::Memory { source_key: source_key.into() }, trust }
    }

    pub fn user_prompt() -> Self {
        Self { source: TextSource::UserPrompt, trust: TrustLevel::Trusted }
    }

    pub fn system() -> Self {
        Self { source: TextSource::System, trust: TrustLevel::Trusted }
    }

    pub fn from_web(url: impl Into<String>) -> Self {
        Self {
            source: TextSource::Web { url: url.into() },
            trust: TrustLevel::Untrusted,
        }
    }

    pub fn from_tool_output(server_url: impl Into<String>, tool_name: impl Into<String>) -> Self {
        Self {
            source: TextSource::ToolOutput {
                server_url: server_url.into(),
                tool_name: tool_name.into(),
            },
            trust: TrustLevel::Untrusted,
        }
    }

    pub fn from_file(path: PathBuf) -> Self {
        Self {
            source: TextSource::File { source_path: path },
            trust: TrustLevel::Untrusted,
        }
    }

    /// G-1 (DD4): path-screened file provenance. A file read from a
    /// committed/tracked in-project source tree (the `project_root` prefix,
    /// e.g. `.elai_cc/`) is `Trusted` — it is first-party code under version
    /// control, not attacker-controlled content. Any path OUTSIDE that root
    /// (absolute external paths, parent-escapes, untracked uploads) is
    /// `Untrusted`, matching the fail-closed default of [`Self::from_file`].
    ///
    /// `project_root` is the canonical workspace prefix the caller already
    /// resolved (the orchestrator joins reads against its `project_root`, so
    /// the screen is "did this read resolve under project_root"). A path that
    /// contains a `..` parent-escape component is treated as `Untrusted`
    /// regardless of prefix (a relative `.elai_cc/../../etc/passwd` must not
    /// be laundered into `Trusted`).
    ///
    /// Grounding: RTBAS ELAI ingest-site mapping (workflow/papers/rtbas-interface.md)
    /// — user/first-party source = Trusted; external file-read = Untrusted.
    pub fn from_file_screened(path: PathBuf, project_root: &std::path::Path) -> Self {
        let trust = if path_is_trusted_source(&path, project_root) {
            TrustLevel::Trusted
        } else {
            TrustLevel::Untrusted
        };
        Self {
            source: TextSource::File { source_path: path },
            trust,
        }
    }

    pub fn from_sandbox(sandbox_id: impl Into<String>) -> Self {
        Self {
            source: TextSource::SandboxOutput { sandbox_id: sandbox_id.into() },
            trust: TrustLevel::Untrusted,
        }
    }

    pub fn from_memory(source_key: impl Into<String>) -> Self {
        Self {
            source: TextSource::Memory { source_key: source_key.into() },
            trust: TrustLevel::Recallable,
        }
    }

    pub fn is_trusted(&self) -> bool {
        matches!(self.trust, TrustLevel::Trusted)
    }

    pub fn is_untrusted(&self) -> bool {
        matches!(self.trust, TrustLevel::Untrusted)
    }
}

/// Wrapper threading a value alongside its provenance. Used in task_runner
/// argv construction sites (9 grep hits per E-37 exploration). The
/// capability gate inspects `provenance()` on every argument.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Provenanced<T> {
    value: T,
    provenance: Provenance,
}

impl<T> Provenanced<T> {
    pub fn new(value: T, provenance: Provenance) -> Self {
        Self { value, provenance }
    }

    /// Coerce a raw value with a default trusted (user-prompt) provenance.
    /// Use for argv that originates from CLI parsing or the dashboard
    /// command bar — NEVER for argv that originates from tool output.
    pub fn trusted(value: T) -> Self {
        Self { value, provenance: Provenance::user_prompt() }
    }

    pub fn value(&self) -> &T {
        &self.value
    }

    pub fn into_value(self) -> T {
        self.value
    }

    pub fn provenance(&self) -> &Provenance {
        &self.provenance
    }

    pub fn is_untrusted(&self) -> bool {
        self.provenance.is_untrusted()
    }

    pub fn map<U, F: FnOnce(T) -> U>(self, f: F) -> Provenanced<U> {
        Provenanced { value: f(self.value), provenance: self.provenance }
    }
}

/// G-1 (DD4): decide whether a file path is trusted first-party source.
///
/// Trusted iff the path, after lexical normalization, starts with
/// `project_root` AND contains no `..` parent-escape component. Pure +
/// deterministic + allocation-light; performs no filesystem access (so it is
/// safe to call on the hot dispatch path and in tests without a real tree).
fn path_is_trusted_source(path: &std::path::Path, project_root: &std::path::Path) -> bool {
    use std::path::Component;
    // A parent-escape anywhere disqualifies (defends against
    // `<root>/../../etc/passwd` being laundered into Trusted).
    if path.components().any(|c| matches!(c, Component::ParentDir)) {
        return false;
    }
    // An empty root means "no trusted tree configured" -> nothing is trusted
    // (fail-closed): never default an unconfigured screen to Trusted.
    if project_root.as_os_str().is_empty() {
        return false;
    }
    path.starts_with(project_root)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn user_prompt_is_trusted() {
        let p = Provenance::user_prompt();
        assert!(p.is_trusted());
        assert!(!p.is_untrusted());
        assert_eq!(p.source.label(), "user_prompt");
        assert_eq!(p.trust.label(), "trusted");
    }

    #[test]
    fn web_is_untrusted() {
        let p = Provenance::from_web("https://attacker.example.com/page");
        assert!(!p.is_trusted());
        assert!(p.is_untrusted());
        assert_eq!(p.source.label(), "web");
    }

    #[test]
    fn memory_is_recallable_not_trusted_not_untrusted() {
        let p = Provenance::from_memory("memory-bank/projectBrief.md");
        assert!(!p.is_trusted());
        assert!(!p.is_untrusted());
        assert_eq!(p.trust, TrustLevel::Recallable);
    }

    #[test]
    fn provenanced_wraps_and_unwraps_value() {
        let pv = Provenanced::trusted("hello".to_string());
        assert_eq!(pv.value(), "hello");
        assert!(pv.provenance().is_trusted());
    }

    #[test]
    fn provenanced_map_preserves_provenance() {
        let pv = Provenanced::new(
            "WORLD".to_string(),
            Provenance::from_web("https://example.com"),
        );
        let pv2 = pv.map(|s| s.to_lowercase());
        assert_eq!(pv2.value(), "world");
        assert!(pv2.is_untrusted());
    }

    #[test]
    fn trust_level_ordering_stable() {
        assert!(TrustLevel::Trusted < TrustLevel::Recallable);
        assert!(TrustLevel::Recallable < TrustLevel::Untrusted);
    }

    #[test]
    fn text_source_label_hash_stable() {
        let a = TextSource::UserPrompt.label_blake3_prefix();
        let b = TextSource::UserPrompt.label_blake3_prefix();
        assert_eq!(a, b);
        let c = TextSource::System.label_blake3_prefix();
        assert_ne!(a, c);
    }

    #[test]
    fn provenance_serde_roundtrip() {
        let p = Provenance::from_tool_output("http://localhost:8200", "search");
        let s = serde_json::to_string(&p).expect("serialize");
        let back: Provenance = serde_json::from_str(&s).expect("deserialize");
        assert_eq!(p, back);
    }

    // Cold-wiring (s-81344): coverage for previously-untested labels,
    // constructors, and Provenanced::new / into_value. Pure + deterministic.

    #[test]
    fn trust_level_labels_exhaustive() {
        assert_eq!(TrustLevel::Trusted.label(), "trusted");
        assert_eq!(TrustLevel::Recallable.label(), "recallable");
        assert_eq!(TrustLevel::Untrusted.label(), "untrusted");
    }

    #[test]
    fn text_source_labels_exhaustive() {
        assert_eq!(TextSource::UserPrompt.label(), "user_prompt");
        assert_eq!(TextSource::System.label(), "system");
        assert_eq!(
            TextSource::ToolOutput {
                server_url: "http://localhost:8200".to_string(),
                tool_name: "search".to_string(),
            }
            .label(),
            "tool_output"
        );
        assert_eq!(
            TextSource::Web { url: "https://e.com".to_string() }.label(),
            "web"
        );
        assert_eq!(
            TextSource::File { source_path: PathBuf::from("/tmp/x") }.label(),
            "file"
        );
        assert_eq!(
            TextSource::SandboxOutput { sandbox_id: "sb-1".to_string() }.label(),
            "sandbox_output"
        );
        assert_eq!(
            TextSource::Memory { source_key: "k".to_string() }.label(),
            "memory"
        );
    }

    #[test]
    fn constructors_set_expected_source_and_trust() {
        let sys = Provenance::system();
        assert!(sys.is_trusted());
        assert_eq!(sys.source.label(), "system");

        let file = Provenance::from_file(PathBuf::from("/home/user/upload.csv"));
        assert!(file.is_untrusted());
        assert_eq!(file.source.label(), "file");

        let sandbox = Provenance::from_sandbox("exec-42");
        assert!(sandbox.is_untrusted());
        assert_eq!(sandbox.source.label(), "sandbox_output");

        let tool = Provenance::from_tool_output("http://localhost", "grep");
        assert!(tool.is_untrusted());
        assert_eq!(tool.source.label(), "tool_output");
    }

    #[test]
    fn provenanced_new_preserves_value_and_untrusted_provenance() {
        let pv = Provenanced::new("secret".to_string(), Provenance::from_sandbox("box-7"));
        assert_eq!(pv.value(), "secret");
        assert!(pv.is_untrusted());
        assert_eq!(pv.provenance().source.label(), "sandbox_output");
        assert_eq!(pv.into_value(), "secret");
    }
}
