#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mod_rs_sorted_lexicographically() {
        let t = BridgeFileTemplate::with_seed(42);
        let spec = BridgeFileSpec {
            kind: BridgeKind::ModRsAggregator,
            target_path: PathBuf::from("crate/mod.rs"),
            module_names: vec!["z".into(), "a".into(), "m".into()],
        };
        let body = t.generate(&spec);
        let lines: Vec<&str> = body.lines().filter(|l| l.starts_with("pub mod")).collect();
        assert_eq!(
            lines,
            vec!["pub mod a;", "pub mod m;", "pub mod z;"]
        );
    }

    #[test]
    fn deterministic_across_runs_with_same_seed() {
        let t1 = BridgeFileTemplate::with_seed(42);
        let t2 = BridgeFileTemplate::with_seed(42);
        let spec = BridgeFileSpec {
            kind: BridgeKind::ModRsAggregator,
            target_path: PathBuf::from("crate/mod.rs"),
            module_names: vec!["alpha".into(), "beta".into(), "gamma".into()],
        };
        assert_eq!(t1.generate(&spec), t2.generate(&spec));
    }

    #[test]
    fn init_py_uses_hash_header_and_python_syntax() {
        let t = BridgeFileTemplate::with_seed(0);
        let spec = BridgeFileSpec {
            kind: BridgeKind::InitPyBarrel,
            target_path: PathBuf::from("pkg/__init__.py"),
            module_names: vec!["one".into(), "two".into()],
        };
        let body = t.generate(&spec);
        assert!(body.starts_with("# Auto-generated"));
        assert!(body.contains("from .one import *"));
        assert!(body.contains("from .two import *"));
    }

    #[test]
    fn index_ts_uses_slash_header_and_ts_syntax() {
        let t = BridgeFileTemplate::with_seed(0);
        let spec = BridgeFileSpec {
            kind: BridgeKind::IndexTsBarrel,
            target_path: PathBuf::from("pkg/index.ts"),
            module_names: vec!["foo".into(), "bar".into()],
        };
        let body = t.generate(&spec);
        assert!(body.starts_with("// Auto-generated"));
        assert!(body.contains("export * from './bar';"));
        assert!(body.contains("export * from './foo';"));
    }

    #[test]
    fn write_bridge_creates_file() {
        let dir = tempfile::tempdir().unwrap();
        let t = BridgeFileTemplate::with_seed(7);
        let spec = BridgeFileSpec {
            kind: BridgeKind::ModRsAggregator,
            target_path: PathBuf::from("mod.rs"),
            module_names: vec!["x".into(), "y".into()],
        };
        let written = t.write_bridge(&spec, dir.path()).unwrap();
        let text = fs::read_to_string(&written).unwrap();
        assert!(text.contains("pub mod x;"));
        assert!(text.contains("pub mod y;"));
    }
}
