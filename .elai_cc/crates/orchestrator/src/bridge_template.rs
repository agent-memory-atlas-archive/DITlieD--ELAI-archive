//! C-32 — BridgeFileTemplate: deterministic orchestrator-written bridge files
//! (mod.rs aggregators, __init__.py barrels, index.ts barrels, Go package
//! docs).
//!
//! Pure text assembly — no LLM, no network, no `rand`. Two calls to
//! [`BridgeFileTemplate::generate`] with the same [`BridgeFileSpec`] and the
//! same `ELAI_SEED` produce byte-identical output (stub_ban + plan
//! DETERMINISTIC_CHECK #4). The seed only enters the header banner; the body
//! text is deterministic by construction (module names sorted
//! lexicographically).
//!
//! Spec anchors (C-32 plan §Task 4):
//!   - `BridgeKind`, `BridgeFileSpec`, `BridgeFileTemplate`.
//!   - `BridgeFileTemplate { seed: u64 }` (ELAI_SEED env, default 0).
//!   - `generate(spec)` -> deterministic String.
//!   - `write_bridge(spec, output_dir)` -> single fs::write.
//!   - `BridgeError`: WriteFailed { path, source: String } (Clone bound per
//!      C-32-decisions D6).

use std::fs;
use std::path::{Path, PathBuf};
use std::sync::Arc;

use serde::{Deserialize, Serialize};
use thiserror::Error;

use crate::determinism::ELAI_SEED_ENV;
use crate::ssb::{BridgeFileGeneratedPayload, Ssb, SsbPayload};

// ---------------------------------------------------------------------------
// Kind / spec
// ---------------------------------------------------------------------------

/// Bridge-file flavour. Each kind has a fixed render template.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum BridgeKind {
    /// Rust `mod.rs` aggregator. Lines look like `pub mod foo;`.
    ModRsAggregator,
    /// Python `__init__.py` barrel. Lines look like `from .foo import *`.
    InitPyBarrel,
    /// TypeScript / JavaScript `index.ts` barrel.
    /// Lines look like `export * from './foo';`.
    IndexTsBarrel,
    /// Go package-doc header. Single `package foo` line plus comment block.
    GoPackageDoc,
}

impl BridgeKind {
    /// Wire-form string used in SSB payloads.
    pub fn as_str(self) -> &'static str {
        match self {
            BridgeKind::ModRsAggregator => "mod_rs_aggregator",
            BridgeKind::InitPyBarrel => "init_py_barrel",
            BridgeKind::IndexTsBarrel => "index_ts_barrel",
            BridgeKind::GoPackageDoc => "go_package_doc",
        }
    }
}

/// Spec consumed by [`BridgeFileTemplate::generate`].
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct BridgeFileSpec {
    pub kind: BridgeKind,
    pub target_path: PathBuf,
    /// Module / sub-package names. Sorted lexicographically by `generate()`
    /// so the input order does not affect determinism.
    pub module_names: Vec<String>,
}

// ---------------------------------------------------------------------------
// Errors
// ---------------------------------------------------------------------------

/// BridgeFileTemplate errors. `source` is `String` (not `io::Error`) so the
/// type derives `Clone` per C-32-decisions D6.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum BridgeError {
    #[error("bridge write to '{path}' failed: {message}")]
    WriteFailed { path: PathBuf, message: String },
}

// ---------------------------------------------------------------------------
// Header banner
// ---------------------------------------------------------------------------

const HEADER_BANNER: &str =
    "// Auto-generated by ELAI BridgeFileTemplate. Do not edit.";

const HEADER_BANNER_HASH: &str =
    "# Auto-generated by ELAI BridgeFileTemplate. Do not edit.";

// ---------------------------------------------------------------------------
// BridgeFileTemplate
// ---------------------------------------------------------------------------

/// Deterministic bridge-file renderer. `seed` is read from `ELAI_SEED`
/// (default 0) but is only used in the header banner — the body text is
/// deterministic by construction.
#[derive(Debug, Clone)]
pub struct BridgeFileTemplate {
    pub seed: u64,
}

impl Default for BridgeFileTemplate {
    fn default() -> Self {
        Self {
            seed: read_elai_seed(),
        }
    }
}

impl BridgeFileTemplate {
    /// Construct with the supplied seed (bypasses the env lookup; used in
    /// the contract test).
    pub fn with_seed(seed: u64) -> Self {
        Self { seed }
    }

    /// Render a bridge-file body. Pure function; no I/O.
    pub fn generate(&self, spec: &BridgeFileSpec) -> String {
        let mut names = spec.module_names.clone();
        names.sort();
        match spec.kind {
            BridgeKind::ModRsAggregator => self.render_mod_rs(&names),
            BridgeKind::InitPyBarrel => self.render_init_py(&names),
            BridgeKind::IndexTsBarrel => self.render_index_ts(&names),
            BridgeKind::GoPackageDoc => self.render_go_doc(&names, spec),
        }
    }

    /// Generate + single `fs::write`. Creates the parent directory if missing.
    pub fn write_bridge(
        &self,
        spec: &BridgeFileSpec,
        output_dir: &Path,
    ) -> Result<PathBuf, BridgeError> {
        let body = self.generate(spec);
        let target = if spec.target_path.is_absolute() {
            spec.target_path.clone()
        } else {
            output_dir.join(&spec.target_path)
        };
        if let Some(parent) = target.parent() {
            if !parent.as_os_str().is_empty() {
                fs::create_dir_all(parent).map_err(|e| BridgeError::WriteFailed {
                    path: target.clone(),
                    message: e.to_string(),
                })?;
            }
        }
        fs::write(&target, body.as_bytes()).map_err(|e| BridgeError::WriteFailed {
            path: target.clone(),
            message: e.to_string(),
        })?;
        Ok(target)
    }

    fn header_slash(&self) -> String {
        format!("{HEADER_BANNER}\n// seed={}\n\n", self.seed)
    }

    fn header_hash(&self) -> String {
        format!("{HEADER_BANNER_HASH}\n# seed={}\n\n", self.seed)
    }

    fn render_mod_rs(&self, names: &[String]) -> String {
        let mut out = self.header_slash();
        for n in names {
            out.push_str(&format!("pub mod {n};\n"));
        }
        out
    }

    fn render_init_py(&self, names: &[String]) -> String {
        let mut out = self.header_hash();
        for n in names {
            out.push_str(&format!("from .{n} import *\n"));
        }
        out
    }

    fn render_index_ts(&self, names: &[String]) -> String {
        let mut out = self.header_slash();
        for n in names {
            out.push_str(&format!("export * from './{n}';\n"));
        }
        out
    }

    fn render_go_doc(&self, names: &[String], spec: &BridgeFileSpec) -> String {
        // Use the target file's parent dir name as the package, fallback
        // to the first module name.
        let package_name = spec
            .target_path
            .parent()
            .and_then(|p| p.file_name())
            .and_then(|f| f.to_str())
            .map(String::from)
            .unwrap_or_else(|| {
                names
                    .first()
                    .cloned()
                    .unwrap_or_else(|| "main".to_string())
            });
        let mut out = self.header_slash();
        out.push_str(&format!("// Package {package_name} aggregates the sub-packages: "));
        out.push_str(&names.join(", "));
        out.push_str(".\n");
        out.push_str(&format!("package {package_name}\n"));
        out
    }
}

// ---------------------------------------------------------------------------
// ELAI_SEED lookup
// ---------------------------------------------------------------------------

fn read_elai_seed() -> u64 {
    match std::env::var(ELAI_SEED_ENV) {
        Ok(v) => v.trim().parse::<u64>().unwrap_or(0),
        Err(_) => 0,
    }
}

// ---------------------------------------------------------------------------
// SSB emit
// ---------------------------------------------------------------------------

/// Emit a `bridge_file_generated` row. Errors silently swallowed.
pub async fn emit_bridge_file_generated_ssb(
    ssb: &Arc<Ssb>,
    agent_id: &str,
    superstep: i64,
    spec: &BridgeFileSpec,
    written_path: &Path,
) {
    let payload = SsbPayload::BridgeFileGenerated(BridgeFileGeneratedPayload {
        kind: spec.kind.as_str().to_string(),
        path: written_path.to_string_lossy().into_owned(),
        module_count: u32::try_from(spec.module_names.len()).unwrap_or(u32::MAX),
    });
    let files = vec![written_path.to_string_lossy().into_owned()];
    let _ = ssb
        .write_payload(agent_id, superstep, payload, files)
        .await;
}

