//! E-41: CODEOWNERS generator.
//!
//! Walks the repo root, applies a small set of deterministic ownership
//! heuristics (extension + directory prefix), and produces a CODEOWNERS
//! file body the caller can write to `.github/CODEOWNERS` or feed to
//! `gh repo edit` via the user's opt-in flow.
//!
//! Heuristics are deliberately conservative — the goal is "give the user
//! a starting point", not "claim authoritative ownership". The output
//! file's header documents the generator + the inputs used so reviewers
//! can audit the suggestions.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

/// Single (path-glob, owner) pair.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodeownersEntry {
    pub glob: String,
    pub owner: String,
}

/// Generate a CODEOWNERS file body from a list of touched files plus a
/// default-owner. The owner string MUST be a GitHub handle (e.g.
/// `@octocat`) or a team handle (e.g. `@org/team`). Pure function.
///
/// Output shape:
/// ```text
/// # Auto-generated by elai pr review gen-codeowners
/// # default-owner: @octocat
/// # entries: 5
///
/// *.rs                     @octocat
/// *.svelte                 @octocat
/// .github/                 @octocat
/// ```
#[must_use]
pub fn generate_codeowners(touched: &[PathBuf], default_owner: &str) -> String {
    let owner = if default_owner.starts_with('@') {
        default_owner.to_string()
    } else {
        format!("@{default_owner}")
    };
    let mut by_pattern: BTreeMap<String, String> = BTreeMap::new();
    for p in touched {
        let pattern = pattern_for(p);
        by_pattern.insert(pattern, owner.clone());
    }
    let entries: Vec<CodeownersEntry> = by_pattern
        .into_iter()
        .map(|(glob, owner)| CodeownersEntry { glob, owner })
        .collect();
    render(&entries, &owner)
}

/// Render a list of entries into a CODEOWNERS body. Header carries the
/// default-owner + count so the user can quickly audit.
#[must_use]
pub fn render(entries: &[CodeownersEntry], default_owner: &str) -> String {
    let mut out = String::new();
    out.push_str("# Auto-generated by elai pr review gen-codeowners\n");
    out.push_str(&format!("# default-owner: {default_owner}\n"));
    out.push_str(&format!("# entries: {}\n\n", entries.len()));
    // Pad the glob column to 24 chars for readability.
    for e in entries {
        let pad_width = if e.glob.len() < 24 { 24 - e.glob.len() } else { 1 };
        out.push_str(&e.glob);
        for _ in 0..pad_width {
            out.push(' ');
        }
        out.push_str(&e.owner);
        out.push('\n');
    }
    out
}

/// Deterministic mapping from a file path to a CODEOWNERS glob. We
/// collapse paths by:
/// - Top-level dir (`.github/`, `crates/`) -> directory glob
/// - File extension (`.rs`, `.svelte`, `.ts`) -> extension glob
/// - Fall-back -> exact path
fn pattern_for(p: &Path) -> String {
    let s = p.to_string_lossy().replace('\\', "/");
    if s.starts_with(".github/") {
        return ".github/".to_string();
    }
    if let Some(ext) = p.extension().and_then(|e| e.to_str()) {
        match ext {
            "rs" | "svelte" | "ts" | "py" | "toml" | "yml" | "yaml" | "json" | "md" => {
                return format!("*.{ext}");
            }
            _ => {}
        }
    }
    // Otherwise return the top-level directory glob.
    let first_segment = s.split('/').next().unwrap_or("");
    if first_segment.is_empty() {
        s
    } else {
        format!("{first_segment}/")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rust_files_collapse_to_extension_glob() {
        let touched = vec![
            PathBuf::from("crates/cli/src/main.rs"),
            PathBuf::from("crates/orchestrator/src/lib.rs"),
        ];
        let body = generate_codeowners(&touched, "octocat");
        assert!(body.contains("*.rs"));
        assert!(body.contains("@octocat"));
    }

    #[test]
    fn github_dir_gets_dir_pattern() {
        let touched = vec![PathBuf::from(".github/workflows/ci.yml")];
        let body = generate_codeowners(&touched, "@team/owners");
        assert!(body.contains(".github/"));
        assert!(body.contains("@team/owners"));
    }

    #[test]
    fn header_renders_count() {
        let touched = vec![
            PathBuf::from("a.rs"),
            PathBuf::from("b.svelte"),
            PathBuf::from("c.ts"),
        ];
        let body = generate_codeowners(&touched, "x");
        assert!(body.contains("# entries: 3\n"));
    }

    #[test]
    fn default_owner_gets_at_prefix() {
        let touched = vec![PathBuf::from("x.rs")];
        let body = generate_codeowners(&touched, "octocat");
        assert!(body.contains("@octocat"));
    }
}
