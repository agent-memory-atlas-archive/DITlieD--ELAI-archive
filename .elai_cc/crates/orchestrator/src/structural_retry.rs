//! C-32 — StructuralRetrySequencer: deterministic structural retry chain
//! fired when [`crate::mini_critic::MiniCriticVerdict::Block`] is observed
//! on a fill body.
//!
//! Four stages run in order:
//!
//!   `Decompose` -> `Template` -> `FewShot` -> `BestOfN`
//!
//! Each stage receives a [`RetryContext`] (project root, language, function
//! signature, accumulated fills) and a candidate body. The stage runs
//! [`crate::mini_critic::MiniCritic::check`] on the result; the first PASS
//! verdict short-circuits with [`StructuralRetryOutcome::Converged`]. If
//! every stage is exhausted, the sequencer evaluates the
//! `AcceptAndComplete` threshold (`completeness_ratio >= 0.5`) and either
//! emits [`StructuralRetryOutcome::AcceptAndComplete`] (when the
//! `FileDisciplineConfig.accept_and_complete_enabled` flag is set) or
//! [`StructuralRetryOutcome::Exhausted`].
//!
//! Stub_ban: NO instructional retry text ("try again", "be careful", ...)
//! is generated by any stage. Each stage is a structural transform — split
//! prompts, template lookups, few-shot prepend, multi-candidate selection.
//! Verified by the contract test `no_instructional_text_in_retry_prompt`.
//!
//! Spec anchors (C-32 plan §Task 3):
//!   - `StructuralRetryStage`, `StructuralRetryPlan`, `StructuralRetryOutcome`.
//!   - `run_sequence(plan, blank_id, ctx)` -> outcome.
//!   - `BestOfN` scoring: compile+2, critic PASS+2, lines+1.

use std::path::PathBuf;
use std::sync::Arc;

use serde::{Deserialize, Serialize};

use crate::mini_critic::{MiniCritic, MiniCriticLanguage, MiniCriticResult, MiniCriticVerdict};
use crate::skeleton_generator::{BlankId, FillResult};
use crate::ssb::{
    Ssb, SsbPayload, StructuralRetryStageAttemptPayload,
};

// ---------------------------------------------------------------------------
// Stage / plan / outcome
// ---------------------------------------------------------------------------

/// Structural retry stage tag. Order in [`StructuralRetryPlan::default`]
/// matches the plan §Task 3 ordering: Decompose -> Template -> FewShot ->
/// BestOfN.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum StructuralRetryStage {
    Decompose,
    Template,
    FewShot,
    BestOfN,
}

impl StructuralRetryStage {
    /// Lowercase wire-form string used in SSB payloads.
    pub fn as_str(self) -> &'static str {
        match self {
            StructuralRetryStage::Decompose => "decompose",
            StructuralRetryStage::Template => "template",
            StructuralRetryStage::FewShot => "few_shot",
            StructuralRetryStage::BestOfN => "best_of_n",
        }
    }
}

/// Ordered list of stages to try plus a cursor.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct StructuralRetryPlan {
    pub stages: Vec<StructuralRetryStage>,
    pub current_stage_idx: usize,
    pub blank_id: BlankId,
}

impl StructuralRetryPlan {
    /// Default plan: all four stages in canonical order.
    pub fn default_for_blank(blank_id: BlankId) -> Self {
        Self {
            stages: vec![
                StructuralRetryStage::Decompose,
                StructuralRetryStage::Template,
                StructuralRetryStage::FewShot,
                StructuralRetryStage::BestOfN,
            ],
            current_stage_idx: 0,
            blank_id,
        }
    }

    /// Returns the stage at `current_stage_idx`, or `None` when exhausted.
    pub fn current_stage(&self) -> Option<&StructuralRetryStage> {
        self.stages.get(self.current_stage_idx)
    }

    /// Advance the cursor. Saturates at `stages.len()` (no panic / no wrap).
    pub fn advance(&mut self) {
        if self.current_stage_idx < self.stages.len() {
            self.current_stage_idx = self.current_stage_idx.saturating_add(1);
        }
    }
}

/// Outcome of a single `run_sequence` invocation.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case", tag = "outcome")]
pub enum StructuralRetryOutcome {
    /// One stage produced a PASS verdict; `fill` is the accepted body.
    Converged { fill: String },
    /// Every stage exhausted and the completeness ratio reached >= 0.5,
    /// AND the opt-in flag is on. Partial buffer is accepted.
    AcceptAndComplete { ratio: f32 },
    /// Every stage exhausted, ratio < 0.5, or opt-in flag off. Caller must
    /// propagate the BLOCK verdict.
    Exhausted,
}

// ---------------------------------------------------------------------------
// RetryContext + Config
// ---------------------------------------------------------------------------

/// Read-only context passed to each stage.
#[derive(Debug, Clone)]
pub struct RetryContext {
    pub project_root: PathBuf,
    pub language: MiniCriticLanguage,
    pub fn_signature: String,
    /// Fills accumulated for the whole skeleton up to this point (used to
    /// compute the completeness_ratio threshold).
    pub existing_fills: Vec<FillResult>,
    /// Total blanks for the parent skeleton. Used to compute the ratio when
    /// every stage exhausts.
    pub total_blanks: usize,
    /// Mirror of `FileDisciplineConfig.accept_and_complete_enabled`
    /// (see C-32-decisions D10).
    pub accept_and_complete_enabled: bool,
}

/// Configuration for [`StructuralRetrySequencer`].
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StructuralRetryConfig {
    /// Number of candidates the BestOfN stage will score.
    pub max_best_of_n: u8,
}

impl Default for StructuralRetryConfig {
    fn default() -> Self {
        Self { max_best_of_n: 3 }
    }
}

/// Threshold for [`StructuralRetryOutcome::AcceptAndComplete`].
/// Plan §Task 1 + §Task 3: ratio >= 0.5 with opt-in flag -> accept.
pub const ACCEPT_AND_COMPLETE_THRESHOLD: f32 = 0.5;

// ---------------------------------------------------------------------------
// Candidate trait — production wiring vs. unit tests
// ---------------------------------------------------------------------------

/// A producer of candidate bodies per stage. Production wiring binds an
/// implementation that drives the per-role LLM and DKG; tests bind a
/// canned candidate map.
pub trait StageCandidates: Send + Sync {
    /// Return a vec of candidate fill bodies for the given stage. Empty
    /// vec means "stage produced no candidate" (treat as Block).
    fn candidates(&self, stage: StructuralRetryStage, ctx: &RetryContext) -> Vec<String>;
}

/// Trivial implementation for tests and bench-mode callers — fixed mapping
/// from stage to candidate list.
#[derive(Debug, Clone, Default)]
pub struct StaticStageCandidates {
    pub decompose: Vec<String>,
    pub template: Vec<String>,
    pub few_shot: Vec<String>,
    pub best_of_n: Vec<String>,
}

impl StaticStageCandidates {
    pub fn empty() -> Self {
        Self {
            decompose: Vec::new(),
            template: Vec::new(),
            few_shot: Vec::new(),
            best_of_n: Vec::new(),
        }
    }
}

impl StageCandidates for StaticStageCandidates {
    fn candidates(&self, stage: StructuralRetryStage, _ctx: &RetryContext) -> Vec<String> {
        match stage {
            StructuralRetryStage::Decompose => self.decompose.clone(),
            StructuralRetryStage::Template => self.template.clone(),
            StructuralRetryStage::FewShot => self.few_shot.clone(),
            StructuralRetryStage::BestOfN => self.best_of_n.clone(),
        }
    }
}

// ---------------------------------------------------------------------------
// StructuralRetrySequencer
// ---------------------------------------------------------------------------

/// Stateless. State lives in the [`StructuralRetryPlan`] cursor + the
/// [`RetryContext`] the caller supplies.
pub struct StructuralRetrySequencer {
    pub config: StructuralRetryConfig,
}

impl Default for StructuralRetrySequencer {
    fn default() -> Self {
        Self::new(StructuralRetryConfig::default())
    }
}

impl StructuralRetrySequencer {
    pub fn new(config: StructuralRetryConfig) -> Self {
        Self { config }
    }

    /// Run the structural retry sequence. The supplied `candidates` producer
    /// is invoked once per stage to obtain candidate bodies. The
    /// `MiniCritic` decides PASS/BLOCK on each candidate. Convergence
    /// short-circuits.
    pub fn run_sequence(
        &self,
        plan: &mut StructuralRetryPlan,
        ctx: &RetryContext,
        critic: &MiniCritic,
        candidates: &dyn StageCandidates,
    ) -> StructuralRetryOutcome {
        while let Some(stage) = plan.current_stage().copied() {
            let bodies = candidates.candidates(stage, ctx);
            let outcome = match stage {
                StructuralRetryStage::BestOfN => {
                    self.run_best_of_n(plan.blank_id, &bodies, ctx.language, critic)
                }
                _ => self.run_single_pick(plan.blank_id, &bodies, ctx.language, critic),
            };
            if let Some(fill) = outcome {
                return StructuralRetryOutcome::Converged { fill };
            }
            plan.advance();
        }
        // Every stage exhausted — decide AcceptAndComplete vs Exhausted.
        let ratio = ratio_with_block_for_current(ctx, plan.blank_id);
        if ctx.accept_and_complete_enabled && ratio >= ACCEPT_AND_COMPLETE_THRESHOLD {
            StructuralRetryOutcome::AcceptAndComplete { ratio }
        } else {
            StructuralRetryOutcome::Exhausted
        }
    }

    /// For Decompose / Template / FewShot stages: take the first candidate
    /// that produces a `MiniCriticVerdict::Pass`.
    fn run_single_pick(
        &self,
        blank_id: BlankId,
        bodies: &[String],
        lang: MiniCriticLanguage,
        critic: &MiniCritic,
    ) -> Option<String> {
        for body in bodies {
            let r = critic.check(blank_id, body, lang);
            if r.verdict == MiniCriticVerdict::Pass {
                return Some(body.clone());
            }
        }
        None
    }

    /// Score every candidate and pick the highest. Scoring:
    ///   compile (tree-sitter fragment parses without ERROR) +2,
    ///   critic verdict PASS +2,
    ///   line count >= MIN_BODY_LINES +1.
    fn run_best_of_n(
        &self,
        blank_id: BlankId,
        bodies: &[String],
        lang: MiniCriticLanguage,
        critic: &MiniCritic,
    ) -> Option<String> {
        let max = self.config.max_best_of_n as usize;
        let mut best: Option<(i32, &String)> = None;
        for body in bodies.iter().take(max) {
            let score = score_candidate(body, lang, critic, blank_id);
            best = match best {
                Some((s, _)) if s >= score => best,
                _ => Some((score, body)),
            };
        }
        match best {
            Some((s, body)) if s > 0 => Some(body.clone()),
            _ => None,
        }
    }
}

fn score_candidate(
    body: &str,
    lang: MiniCriticLanguage,
    critic: &MiniCritic,
    blank_id: BlankId,
) -> i32 {
    let mut score = 0i32;
    // Compile bonus = fragment parses without ERROR (DRIFT D9). The critic
    // owns the parse so we reuse it.
    let parse_critic = MiniCritic::new();
    let parse_result: MiniCriticResult = parse_critic.check(blank_id, body, lang);
    if parse_result.verdict != MiniCriticVerdict::Block
        || !parse_result.reason.starts_with("parse_error")
    {
        // Treat anything not flagged as a parse_error as "compiles".
        score = score.saturating_add(2);
    }
    // Critic PASS bonus.
    let r = critic.check(blank_id, body, lang);
    if r.verdict == MiniCriticVerdict::Pass {
        score = score.saturating_add(2);
    }
    // Line count bonus.
    if body.lines().count() >= crate::mini_critic::MIN_BODY_LINES {
        score = score.saturating_add(1);
    }
    score
}

/// Treat the current blank as BLOCKed when computing the ratio (the stage
/// chain just exhausted on it).
fn ratio_with_block_for_current(ctx: &RetryContext, blank: BlankId) -> f32 {
    if ctx.total_blanks == 0 {
        return 1.0;
    }
    let mut non_block = 0usize;
    for f in &ctx.existing_fills {
        if f.blank_id == blank {
            // Current blank is being marked BLOCK by this sequence.
            continue;
        }
        if f.mini_critic_verdict != MiniCriticVerdict::Block {
            non_block += 1;
        }
    }
    let denom = ctx.total_blanks as f32;
    (non_block as f32 / denom).clamp(0.0, 1.0)
}

// ---------------------------------------------------------------------------
