#[cfg(test)]
mod tests {
    use super::*;

    fn ctx(total: usize, accept_flag: bool) -> RetryContext {
        RetryContext {
            project_root: PathBuf::from("/tmp"),
            language: MiniCriticLanguage::Rust,
            fn_signature: "fn probe()".into(),
            existing_fills: Vec::new(),
            total_blanks: total,
            accept_and_complete_enabled: accept_flag,
        }
    }

    #[test]
    fn default_plan_order() {
        let p = StructuralRetryPlan::default_for_blank(BlankId(1));
        assert_eq!(
            p.stages,
            vec![
                StructuralRetryStage::Decompose,
                StructuralRetryStage::Template,
                StructuralRetryStage::FewShot,
                StructuralRetryStage::BestOfN,
            ]
        );
    }

    #[test]
    fn template_stage_converges_when_candidate_passes() {
        let seq = StructuralRetrySequencer::default();
        let critic = MiniCritic::without_tree_sitter();
        let mut plan = StructuralRetryPlan::default_for_blank(BlankId(1));
        let candidates = StaticStageCandidates {
            decompose: vec![],
            template: vec!["let x = 1;\nlet y = 2;\nx + y".into()],
            few_shot: vec![],
            best_of_n: vec![],
        };
        let outcome = seq.run_sequence(&mut plan, &ctx(2, false), &critic, &candidates);
        match outcome {
            StructuralRetryOutcome::Converged { fill } => {
                assert!(fill.contains("let x = 1"));
            }
            other => panic!("expected Converged, got {other:?}"),
        }
    }

    #[test]
    fn exhausted_when_no_candidates_and_flag_off() {
        let seq = StructuralRetrySequencer::default();
        let critic = MiniCritic::without_tree_sitter();
        let mut plan = StructuralRetryPlan::default_for_blank(BlankId(1));
        let candidates = StaticStageCandidates::empty();
        let outcome = seq.run_sequence(&mut plan, &ctx(2, false), &critic, &candidates);
        assert_eq!(outcome, StructuralRetryOutcome::Exhausted);
    }

    #[test]
    fn accept_and_complete_when_flag_on_and_ratio_meets_threshold() {
        let seq = StructuralRetrySequencer::default();
        let critic = MiniCritic::without_tree_sitter();
        let mut plan = StructuralRetryPlan::default_for_blank(BlankId(2));
        let candidates = StaticStageCandidates::empty();
        // 1 prior PASS out of 2 blanks total -> ratio 0.5 (current blank
        // is currently being marked BLOCK).
        let mut c = ctx(2, true);
        c.existing_fills.push(FillResult {
            blank_id: BlankId(1),
            body: "ok".into(),
            mini_critic_verdict: MiniCriticVerdict::Pass,
        });
        let outcome = seq.run_sequence(&mut plan, &c, &critic, &candidates);
        match outcome {
            StructuralRetryOutcome::AcceptAndComplete { ratio } => {
                assert!((ratio - 0.5).abs() < f32::EPSILON);
            }
            other => panic!("expected AcceptAndComplete, got {other:?}"),
        }
    }

    #[test]
    fn accept_and_complete_threshold_strict_below() {
        let seq = StructuralRetrySequencer::default();
        let critic = MiniCritic::without_tree_sitter();
        let mut plan = StructuralRetryPlan::default_for_blank(BlankId(3));
        let candidates = StaticStageCandidates::empty();
        // 1 prior PASS out of 3 blanks -> ratio 0.333... (below 0.5).
        let mut c = ctx(3, true);
        c.existing_fills.push(FillResult {
            blank_id: BlankId(1),
            body: "ok".into(),
            mini_critic_verdict: MiniCriticVerdict::Pass,
        });
        let outcome = seq.run_sequence(&mut plan, &c, &critic, &candidates);
        assert_eq!(outcome, StructuralRetryOutcome::Exhausted);
    }
}
