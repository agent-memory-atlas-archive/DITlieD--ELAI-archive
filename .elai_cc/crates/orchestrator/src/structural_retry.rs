/// Emit a `structural_retry_stage_attempt` row. Errors silently swallowed.
pub async fn emit_stage_attempt_ssb(
    ssb: &Arc<Ssb>,
    agent_id: &str,
    superstep: i64,
    blank_id: BlankId,
    stage: StructuralRetryStage,
    attempt: u32,
    outcome: &str,
) {
    let payload = SsbPayload::StructuralRetryStageAttempt(StructuralRetryStageAttemptPayload {
        blank_id: blank_id.0,
        stage: stage.as_str().to_string(),
        attempt,
        outcome: outcome.to_string(),
    });
    let _ = ssb
        .write_payload(agent_id, superstep, payload, Vec::new())
        .await;
}

