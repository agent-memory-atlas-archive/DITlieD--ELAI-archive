//! I-3: SSB write-loop throughput runner.
//!
//! Drives N sequential `write_payload` calls against an isolated in-process
//! `Ssb` instance (tempfile SQLite, WAL mode), measures wall-clock
//! inserts/sec, and writes `metrics/phase_I3.toml` (ID-5: non-deterministic
//! timing — recorded, never asserted as a pass/fail criterion).
//!
//! # Wiring discipline
//!
//! This runner exercises the REAL SSB write path (single-writer task, WAL
//! pragmas, BEGIN IMMEDIATE transaction) — not a mock or a direct
//! `rusqlite::Connection::execute` call. The measured number is therefore
//! the baseline for any future throughput claim (I-plan ID-5: no paper
//! number carried as a target; the TOML records the measured number and
//! that becomes the ID-5 baseline).
//!
//! Runtime: `#[tokio::test(flavor = "multi_thread")]` — mandatory because
//! `Ssb::new` spawns a tokio task that requires a multi-thread reactor
//! (gotcha SSB_NEW_MUST_BE_BUILT_INSIDE_BLOCK_ON_MULTI_THREAD_RUNTIME).

/// Suite label embedded in the TOML output.
pub const SUITE_LABEL: &str = "ssb_write_loop_throughput";

// ---------------------------------------------------------------------------
// #[cfg(test)] — benchmark + TOML write
// ---------------------------------------------------------------------------

#[cfg(test)]
mod tests {
    use super::SUITE_LABEL;
    use crate::ssb::{FileReadPayload, Ssb, SsbConfig, SsbPayload};
    use elai_core::clock::SeededClock;
    use std::sync::Arc;

    /// Number of sequential inserts to drive through the write loop.
    const N_INSERTS: usize = 10_000;

    /// Run the SSB write-loop throughput benchmark and write the measured
    /// result to `metrics/phase_I3.toml` (ID-5: non-deterministic timing).
    ///
    /// Asserts `inserts_per_sec > 0` (the write loop completed without error)
    /// but does NOT assert any throughput floor (no paper number as target).
    #[tokio::test(flavor = "multi_thread")]
    async fn collect_i3_metrics() {
        let dir = tempfile::TempDir::new().expect("tempdir for SSB bench");
        let db_path = dir.path().join("ssb_throughput_bench.db");

        let cfg = SsbConfig {
            db_path,
            pool_size: Some(2),
            project_id: "bench-i3".to_string(),
            session_id: "ssb-throughput-runner".to_string(),
        };
        let clock: Arc<dyn elai_core::clock::ClockProvider> = Arc::new(SeededClock::new());
        let ssb = Ssb::new(cfg, clock).expect("Ssb::new for throughput bench");

        // Drive N sequential inserts; measure wall-clock time.
        let t0 = std::time::Instant::now();
        for i in 0..N_INSERTS {
            ssb.write_payload(
                "bench-agent",
                i64::try_from(i).unwrap_or(i64::MAX),
                SsbPayload::FileRead(FileReadPayload {
                    path: format!("bench/file_{i}.rs"),
                }),
                vec![],
            )
            .await
            .expect("write_payload must not fail during bench");
        }
        let elapsed = t0.elapsed();
        drop(dir);

        let elapsed_secs = elapsed.as_secs_f64();
        let inserts_per_sec = if elapsed_secs > 0.0 {
            N_INSERTS as f64 / elapsed_secs
        } else {
            f64::INFINITY
        };

        assert!(
            inserts_per_sec > 0.0,
            "inserts_per_sec must be positive (write loop ran)"
        );

        // -------------------------------------------------------------------
        // Write metrics/phase_I3.toml — follow pipeline_builder_bench.rs pattern
        // -------------------------------------------------------------------
        let ws_root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .and_then(|p| p.parent())
            .unwrap_or_else(|| std::path::Path::new("."));
        let metrics_path = ws_root.join("metrics").join("phase_I3.toml");

        if let Some(parent) = metrics_path.parent() {
            let _ = std::fs::create_dir_all(parent);
        }

        let toml_content = format!(
            r#"# I-3: SSB write-loop throughput (atomic checkpoint saves + measured throughput)
# Generated by ssb_throughput_runner::tests::collect_i3_metrics
# ID-5: non-deterministic wall-clock timing -- recorded as baseline, NOT asserted.
# Recomputable: cargo test -p elai-orchestrator -- benchmarks::ssb_throughput_runner::tests::collect_i3_metrics

[measured]
suite = "{suite}"
n_inserts = {n_inserts}
elapsed_secs = {elapsed_secs:.6}
inserts_per_sec = {ips:.2}
note = "non-deterministic -- wall clock; asserted only as > 0"

[context]
host_os = "windows"
write_path = "ssb single-writer task (WAL mode, BEGIN IMMEDIATE, sequential)"
payload_variant = "FileRead (path string only -- minimal bytes per insert)"
clock = "SeededClock (deterministic tick; no SystemTime::now in the measured path)"
atomic_hardening = "I-3 Phase-3C: all 8 checkpoint write sites now use tmp+sync_all+rename"
"#,
            suite = SUITE_LABEL,
            n_inserts = N_INSERTS,
            elapsed_secs = elapsed_secs,
            ips = inserts_per_sec,
        );

        std::fs::write(&metrics_path, &toml_content).expect("write metrics/phase_I3.toml");

        println!(
            "I-3 throughput: {} inserts in {:.3}s = {:.0} inserts/sec; TOML written to {}",
            N_INSERTS,
            elapsed_secs,
            inserts_per_sec,
            metrics_path.display()
        );
    }
}
