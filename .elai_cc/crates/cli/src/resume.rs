pub(crate) fn resume_session(session_path: &Path, commands: &[String], output_format: CliOutputFormat) {
    let resolved_path = if session_path.exists() {
        session_path.to_path_buf()
    } else {
        match handoff::resolve_session_reference(&session_path.display().to_string()) {
            Ok(handle) => handle.path,
            Err(error) => {
                eprintln!("failed to restore session: {error}");
                std::process::exit(1);
            }
        }
    };

    let session = match Session::load_from_path(&resolved_path) {
        Ok(session) => session,
        Err(error) => {
            eprintln!("failed to restore session: {error}");
            std::process::exit(1);
        }
    };

    if commands.is_empty() {
        println!(
            "Restored session from {} ({} messages).",
            resolved_path.display(),
            session.messages.len()
        );
        return;
    }

    let mut session = session;
    for raw_command in commands {
        let command = match SlashCommand::parse(raw_command) {
            Ok(Some(command)) => command,
            Ok(None) => {
                eprintln!("unsupported resumed command: {raw_command}");
                std::process::exit(2);
            }
            Err(error) => {
                eprintln!("{error}");
                std::process::exit(2);
            }
        };
        match run_resume_command(&resolved_path, &session, &command) {
            Ok(ResumeCommandOutcome {
                session: next_session,
                message,
            }) => {
                session = next_session;
                if let Some(message) = message {
                    if output_format == CliOutputFormat::Json
                        && matches!(command, SlashCommand::Status)
                    {
                        let tracker = {
                            let mut t = UsageTracker::new();
                            for m in &session.messages { if let Some(u) = m.usage { t.record(u); } }
                            t
                        };
                        let usage = tracker.cumulative_usage();
                        if let Ok(context) = status_context(Some(&resolved_path)) {
                            let value = json!({
                                "kind": "status",
                                "messages": session.messages.len(),
                                "turns": tracker.turns(),
                                "latest_total": tracker.current_turn_usage().total_tokens(),
                                "cumulative_input": usage.input_tokens,
                                "cumulative_output": usage.output_tokens,
                                "cumulative_total": usage.total_tokens(),
                                "workspace": {
                                    "cwd": context.cwd,
                                    "project_root": context.project_root,
                                    "git_branch": context.git_branch,
                                    "git_state": context.git_summary.headline(),
                                    "session": context.session_path.as_ref().map_or_else(|| "live-repl".to_string(), |path| path.display().to_string()),
                                }
                            });
                            // json!() produces a Value; to_string_pretty on a Value is infallible.
                            println!(
                                "{}",
                                serde_json::to_string_pretty(&value)
                                    .expect("json! Value serialization is infallible")
                            );
                        }
                    } else {
                        println!("{message}");
                    }
                }
            }
            Err(error) => {
                eprintln!("{error}");
                std::process::exit(2);
            }
        }
    }
}

