"""E-45 -- Pydantic typed-boundary models for the sidecar HTTP surface.

Mirrors the orchestrator's serde-serialized shapes (Anthropic-protocol
`/v1/messages` request + response) so the sidecar can validate inbound
requests + serialize outbound responses with explicit field
declarations instead of dict-literal construction.

Per D-10 DECISION-8, the orchestrator-side Rust structs are the
authoritative shape; the Pydantic models here are the lint-the-mirror
side of the same discipline. The `cross_lang_drift::DriftDetector`
walks both sides via the `sidecar_orchestrator_schemas` pair entry in
`cross-lang-pairs.toml`.

Two surfaces:
* `messages` -- the hand-authored Pydantic facade (legacy, source-of-
  truth until _generated is regenerated against a live
  datamodel-codegen run). Consumed by `server.handle_messages`.
* `_generated` (re-exported as `generated`) -- E-45 Tranche 8B
  auto-generated mirror produced by datamodel-code-generator from the
  Rust-side JSON Schema fixtures under
  `crates/orchestrator/tests/schemas/`. Stubs until first regen via
  `.claude/tools/regen_sidecar_schemas.py`.

SCHEMA_VERSION pinned to the orchestrator's `SCHEMA_VERSION_PUBLIC`
constant (currently 191 -- bumped from 138 in Tranche 8 to close the
E-45 drift gap flagged by exploration tranche8-E45-wiring.md). Bump in
lockstep with `crates/orchestrator/src/ssb.rs::SCHEMA_VERSION`.
"""

